#!/usr/bin/env python3
"""PreToolUse safety guard for the restaurant project.

Claude Code sends the tool call it is ABOUT to make as JSON on stdin.

    exit 0  -> no objection (the normal permission flow continues)
    exit 2  -> BLOCK the tool call; whatever we print to stderr is shown
               to Claude as the reason, so it can change course

WARNING: in Claude Code, exit code 1 does NOT block anything. A Python crash
exits with 1, so we wrap everything and turn crashes into exit 2 ("fail closed").
"""
import json
import re
import sys

SAFE_ENV_FILES = {".env.example", ".env.sample", ".env.template"}
ENV_FILE_NAME = re.compile(r"^\.env(\..+)?$", re.IGNORECASE)
# a ".env" token inside a shell command, e.g. `cat .env`, `git add ./.env.local`
ENV_IN_COMMAND = re.compile(r"(?<![\w.-])\.env(?:\.[\w-]+)*(?![\w-])", re.IGNORECASE)

# (pattern, human explanation). Matched against Bash AND PowerShell commands.
DANGEROUS_COMMANDS = [
    (r"\brm\b(?=[^|;&]*(?:\s-[a-zA-Z]*[rR]|\s--recursive))(?=[^|;&]*(?:\s-[a-zA-Z]*f|\s--force))",
     "recursive force delete (rm -rf)"),
    (r"Remove-Item\b[^|;&]*-Recurse", "recursive delete (Remove-Item -Recurse)"),
    (r"\b(?:rmdir|rd)\s+/s\b", "recursive directory delete (rmdir /s)"),
    (r"\bdel\s+[^|;&]*/s\b", "recursive delete (del /s)"),
    (r"\bgit\s+push\b[^|;&]*(?:--force\b|--force-with-lease\b|\s-f\b)", "force push"),
    (r"\bgit\s+reset\s+--hard\b", "git reset --hard (throws away uncommitted work)"),
    (r"\bgit\s+clean\b[^|;&]*\s-[a-zA-Z]*f", "git clean -f (deletes untracked files)"),
    (r"manage\.py\s+flush\b", "manage.py flush (empties the whole database)"),
    (r"\b(?:DROP\s+(?:TABLE|DATABASE|SCHEMA)|TRUNCATE\s+TABLE)\b", "destructive SQL"),
    (r"\b(?:curl|wget|iwr|Invoke-WebRequest)\b[^|]*\|\s*(?:sh|bash|iex|Invoke-Expression)\b",
     "piping a download straight into a shell"),
]


def block(message):
    print(f"BLOCKED by .claude/hooks/guard.py: {message}", file=sys.stderr)
    sys.exit(2)


def check_file_path(tool, path):
    normalized = path.replace("\\", "/")
    parts = normalized.split("/")
    name = parts[-1]
    folders = parts[:-1]

    if ENV_FILE_NAME.match(name) and name.lower() not in SAFE_ENV_FILES:
        block(f"{tool} on '{name}' is not allowed. It holds secrets (SECRET_KEY, Stripe and "
              "SendGrid keys). Ask the human to change it, or put placeholders in .env.example.")
    if ".git" in folders:
        block(f"{tool} inside .git/ is not allowed. Use normal git commands instead.")
    if tool in ("Edit", "Write") and "staticfiles" in folders:
        block("staticfiles/ is generated by `collectstatic`. Edit the source in static/ and "
              "re-run collectstatic instead.")


def check_command(command):
    for match in ENV_IN_COMMAND.finditer(command):
        if match.group(0).lower() not in SAFE_ENV_FILES:
            block(f"this command touches '{match.group(0)}', which holds secrets. Ask the human "
                  "to run it. (To ignore .env in git, use the Edit tool on .gitignore - that is allowed.)")
    for pattern, why in DANGEROUS_COMMANDS:
        if re.search(pattern, command, re.IGNORECASE):
            block(f"{why}. If this is truly needed, ask the human to run it themselves.")


def main():
    try:
        event = json.load(sys.stdin)
    except Exception as exc:  # cannot understand the request -> do not wave it through
        block(f"could not read the hook input ({exc!r}); failing closed.")
    tool = event.get("tool_name", "")
    tool_input = event.get("tool_input") or {}

    if tool in ("Read", "Edit", "Write"):
        path = tool_input.get("file_path")
        if path:
            check_file_path(tool, path)
    elif tool in ("Bash", "PowerShell"):
        command = tool_input.get("command")
        if command:
            check_command(command)
    sys.exit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception as exc:
        block(f"guard crashed ({exc!r}); failing closed so nothing slips through.")
